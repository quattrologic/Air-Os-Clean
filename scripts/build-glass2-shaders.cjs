'use strict';
const fs=require('node:fs'),path=require('node:path');const root=path.resolve(__dirname,'..');
const shape=`
uniform float airEdgeMode;
uniform float airEdgeInset;
uniform vec4 airCorners;
uniform vec2 airSourceScale;
float airBox(vec2 p,vec2 hs,float r){vec2 q=abs(p)-hs+r;return length(max(q,0.0))+min(max(q.x,q.y),0.0)-r;}
float airDistance(vec2 p){
 vec2 q=p-vec2(airEdgeInset,0.0)-glassSize*.5;
 float r=q.y<0.0?(q.x<0.0?airCorners.x:airCorners.y):(q.x<0.0?airCorners.w:airCorners.z);
 float d=airBox(q,glassSize*.5,min(r,min(glassSize.x,glassSize.y)*.5));
 if(airEdgeMode<.5)return d;
 float cy=airEdgeMode<1.5?glassSize.y-12.0:12.0;
 float by=airEdgeMode<1.5?glassSize.y-6.0:6.0;
 float l=max(airBox(p-vec2(6.0,by),vec2(6.0),0.0),12.25-length(p-vec2(0.0,cy)));
 float rr=max(airBox(p-vec2(glassSize.x+18.0,by),vec2(6.0),0.0),12.25-length(p-vec2(glassSize.x+24.0,cy)));
 return min(d,min(l,rr));
}
vec2 airNormal(vec2 p){vec2 g=vec2(airDistance(p+vec2(.5,0.0))-airDistance(p-vec2(.5,0.0)),airDistance(p+vec2(0.0,.5))-airDistance(p-vec2(0.0,.5)));return length(g)>.0001?normalize(g):vec2(0.0,-1.0);}
`;
function port(file,contour=false){let s=fs.readFileSync(path.join(root,file),'utf8');s=s.replace('#version 440','#version 300 es\nprecision highp float;\nprecision highp int;').replace(/layout\(location = 0\) (in|out)/g,'$1').replace(/layout\(binding = 1\) uniform/g,'uniform');
 s=s.replace(/layout\(std140, binding = 0\) uniform buf \{([\s\S]*?)\};/,(_,block)=>[...block.matchAll(/^\s*(mat4|vec[234]|float)\s+(\w+)\s*;/gm)].map(m=>'uniform '+m[1]+' '+m[2]+';').join('\n'));
 const helper=contour?'uniform vec2 glassSize;\n'+shape:shape;
 const i=s.indexOf(contour?'float sdRoundRect':'const int');s=s.slice(0,i)+helper+'\n'+s.slice(i);
 if(contour)s=s.replace('sdRoundRect(p - c, c - pad, cornerR)','airDistance(p)');
 else{s=s.replace('vec2 q  = p - vec2(pad) - hs;','vec2 q  = p - vec2(pad) - hs - vec2(airEdgeInset,0.0);').replace('roundBox(q, hs, r)','airDistance(p)').replace('roundBox(q - vec2(0.0, 3.0), hs, r)','airDistance(p - vec2(0.0,3.0))');s=s.replace(/vec2 g\s*=\s*\(length\(m\)[\s\S]*?;/,'vec2 g = airNormal(p);');s=s.replace('(pItem + srcOffset) / srcSize','(pItem * airSourceScale + srcOffset) / srcSize');}
 return s;
}
const shaders={liquid:port('third_party/deep-port/liquidglass.frag'),dock:port('third_party/glass2/dockglass.frag'),contour:port('third_party/glass2/contourglow.frag',true)};
const text='/* MacShell MIT Copyright (c) 2026 Rickky. GLSL ES / Air-OS shape adapters generated by scripts/build-glass2-shaders.cjs. */\nwindow.airGlass2Shaders='+JSON.stringify(shaders)+';\n';
fs.writeFileSync(path.join(root,'macshell-glass2-shaders.js'),text);
module.exports={port};
